import { createReadStream, writeFileSync } from 'node:fs'
import { createInterface } from 'node:readline'

const input = process.argv[2]
if (!input) {
  console.error('Usage: node scripts/buildWordList.mjs path/to/saldo-file')
  process.exit(1)
}

const found = new Set()

// Keep only lowercase 5-letter words: no proper nouns, hyphens or spaces.
function add(form) {
  if (/^[a-zåäö]{5}$/.test(form)) found.add(form.toUpperCase())
}

const lines = createInterface({
  input: createReadStream(input, 'utf8'),
  crlfDelay: Infinity,
})

for await (const line of lines) {
  // XML: written forms are stored as attributes.
  for (const m of line.matchAll(/att="writtenForm"\s+val="([^"]*)"/g)) add(m[1])
  // Plain text: lemgrams look like "skola..nn.1".
  for (const m of line.matchAll(/(?:^|\s)([^\s.]+)\.\.[a-z]+\.\d+/g)) add(m[1])
}

const words = [...found].sort((a, b) => a.localeCompare(b, 'sv'))

writeFileSync(
  'src/game/validGuesses.ts',
  `// Generated by scripts/buildWordList.mjs from SALDO.\n` +
    `// Språkbanken Text, University of Gothenburg.\n` +
    `export const VALID_GUESS_LIST = '${words.join(' ')}'\n`,
)

console.log(`Wrote ${words.length} words to src/game/validGuesses.ts`)